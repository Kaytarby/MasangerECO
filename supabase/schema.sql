CREATE TABLE IF NOT EXISTS public.eco_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  name TEXT NOT NULL,
  bio TEXT NOT NULL DEFAULT '',
  avatar TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.eco_chats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('direct', 'group')),
  name TEXT,
  avatar TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.eco_chat_participants (
  chat_id BIGINT NOT NULL REFERENCES public.eco_chats(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.eco_users(id) ON DELETE CASCADE,
  last_read_at TIMESTAMPTZ,
  PRIMARY KEY (chat_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.eco_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id BIGINT NOT NULL REFERENCES public.eco_chats(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES public.eco_users(id) ON DELETE CASCADE,
  text TEXT,
  image_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_eco_messages_chat_id
  ON public.eco_messages (chat_id, id);

CREATE INDEX IF NOT EXISTS idx_eco_participants_user_id
  ON public.eco_chat_participants (user_id);

CREATE INDEX IF NOT EXISTS idx_eco_participants_chat_id
  ON public.eco_chat_participants (chat_id);

-- Включаем RLS: доступ идёт только через серверный ключ (service_role),
-- поэтому пароли и переписки закрыты от прямого публичного доступа.
ALTER TABLE public.eco_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eco_chats ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eco_chat_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eco_messages ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.eco_users TO service_role;
GRANT ALL ON TABLE public.eco_chats TO service_role;
GRANT ALL ON TABLE public.eco_chat_participants TO service_role;
GRANT ALL ON TABLE public.eco_messages TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

